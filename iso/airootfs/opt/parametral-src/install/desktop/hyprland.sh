#!/usr/bin/env bash
# desktop/hyprland.sh — the Hyprland edition: Hyprland + UWSM + Noctalia.
#
# Called by install/74-desktop.sh in the installed system (arch-chroot). Hyprland is the
# compositor, Noctalia (MIT) is the shell, and every piece of the look is a file under
# /etc/parametral/hypr so a btrfs snapshot restores the whole desktop.
#
#   bash install/desktop/hyprland.sh --plan   print what would be installed, touch nothing
#   bash install/desktop/hyprland.sh          install (root, installed system)
set -Eeuo pipefail

SRC="${SRC:-$(cd "$(dirname "$0")/../.." && pwd)}"
APPEARANCE="${PARAMETRAL_APPEARANCE:-dark}"
PARAMETRAL_USER="${PARAMETRAL_USER:-}"

PACKAGES=(
  hyprland
  hyprlock
  hypridle
  uwsm
  noctalia
  fuzzel
  xdg-desktop-portal-hyprland
  xdg-desktop-portal-gtk
  polkit-kde-agent
  wl-clipboard
  grim
  slurp
  qt6ct
  adw-gtk-theme
  papirus-icon-theme
  inter-font
  ttf-ibm-plex
  noto-fonts
  noto-fonts-emoji
  brightnessctl
  playerctl
  xdg-user-dirs
  xdg-utils
  libnotify
)

if [ "${1:-}" = "--plan" ]; then
  cat <<EOF
edition=hyprland
session=parametral
session-file=/usr/share/wayland-sessions/parametral.desktop
packages=${PACKAGES[*]}
EOF
  exit 0
fi

[ "$(id -u)" -eq 0 ] || { echo "run as root" >&2; exit 1; }
case "$APPEARANCE" in
  dark|light) ;;
  *) echo "PARAMETRAL_APPEARANCE must be dark or light" >&2; exit 2 ;;
esac

echo "==> Hyprland + Noctalia paketleri"
pacman -S --needed --noconfirm "${PACKAGES[@]}"

echo "==> Hyprland modülleri"
install -d /etc/parametral/hypr
for module in variables environment monitors inputs appearance binds windowrules workspaces shell; do
  install -m 0644 "$SRC/branding/hypr/$module.lua" "/etc/parametral/hypr/$module.lua"
done
install -m 0644 "$SRC/branding/hypr/parametral.lua" /etc/parametral/hypr/parametral.lua
install -m 0644 "$SRC/branding/hypr/hyprlock.conf" /etc/parametral/hypr/hyprlock.conf

# The palette is generated here, not chosen in Lua: the installer has already asked dark or
# light, and a config that silently ignores that answer is worse than no theme option.
if [ "$APPEARANCE" = "light" ]; then
  WALLPAPER="/usr/share/wallpapers/Parametral/contents/images/2560x1440-light.png"
  GTK_THEME="adw-gtk3"
  ICON_THEME="Papirus"
  PALETTE='    graphite = "efe7d9ff",
    surface  = "f4efe6ff",
    card     = "eae2d5ff",
    amber    = "8a5f14ff",
    edge     = "cfc3adff",
    text     = "1e2228ff",'
else
  WALLPAPER="/usr/share/wallpapers/Parametral/contents/images/2560x1440.png"
  GTK_THEME="adw-gtk3-dark"
  ICON_THEME="Papirus-Dark"
  PALETTE='    graphite = "0b0f14ff",
    surface  = "12171eff",
    card     = "1a2029ff",
    amber    = "e0a93bff",
    edge     = "2a323cff",
    text     = "e9e4d8ff",'
fi

cat > /etc/parametral/hypr/theme.lua <<EOF
-- GENERATED by install/desktop/hyprland.sh — appearance: $APPEARANCE
-- Source of truth for the palette: branding/tokens.json. Change the installer answer or
-- token file and regenerate; do not hand-edit a hex value into the other Lua modules.
return {
  appearance = "$APPEARANCE",
  palette = {
$PALETTE
  },
  wallpaper = "$WALLPAPER",
  gtk_theme = "$GTK_THEME",
  icon_theme = "$ICON_THEME",
}
EOF

chmod 755 /etc/parametral /etc/parametral/hypr
chmod 0644 /etc/parametral/hypr/*.lua /etc/parametral/hypr/hyprlock.conf

echo "==> Oturum başlatıcı ve yardımcılar"
install -m 0755 "$SRC/branding/hypr/parametral-session" /usr/local/bin/parametral-session
install -m 0755 "$SRC/branding/hypr/parametral-wallpaper" /usr/local/bin/parametral-wallpaper
install -m 0755 "$SRC/branding/hypr/parametral-launcher" /usr/local/bin/parametral-launcher

# Per-session wallpaper copy: the image tree stays root-owned, only the shell's copy is writable.
printf 'd /run/parametral 1777 root root -\n' > /usr/lib/tmpfiles.d/parametral-wallpaper.conf

echo "==> Parametral Shell (deneysel QML yüzeyleri; Noctalia başlatılır)"
install -d /usr/share/parametral/shell
install -m 0644 "$SRC/shell/shell.qml"    /usr/share/parametral/shell/shell.qml
install -m 0644 "$SRC/shell/launcher.qml" /usr/share/parametral/shell/launcher.qml
install -m 0644 "$SRC/shell/polkit.qml"   /usr/share/parametral/shell/polkit.qml
install -m 0644 "$SRC/shell/Theme.js"     /usr/share/parametral/shell/Theme.js

echo "==> Duvar kağıtları (plaka çizilmiş, ekran boyutuna göre)"
install -d /usr/share/wallpapers/Parametral/contents/images
for size in 2560x1440 2560x1440-light 1920x1080 1920x1080-light 1280x800 1280x800-light; do
  install -m 0644 "$SRC/branding/wallpapers/$size.png" \
    "/usr/share/wallpapers/Parametral/contents/images/$size.png"
done

echo "==> İmleç + başlatıcı markı"
if [ -d "$SRC/branding/cursors/Parametral" ]; then
  rm -rf /usr/share/icons/Parametral
  cp -r "$SRC/branding/cursors/Parametral" /usr/share/icons/Parametral
fi
install -d /usr/share/icons/hicolor/scalable/apps
install -m 0644 "$SRC/branding/icons/parametral-start.svg" \
  /usr/share/icons/hicolor/scalable/apps/parametral-start.svg

echo "==> Oturum girdisi (uwsm + start-hyprland)"
install -d /usr/share/wayland-sessions
cat > /usr/share/wayland-sessions/parametral.desktop <<'EOF'
[Desktop Entry]
Name=Parametral
Comment=Hyprland ve Noctalia ile Parametral OS oturumu
Exec=/usr/local/bin/parametral-session
TryExec=/usr/local/bin/parametral-session
Type=Application
DesktopNames=Parametral
Keywords=Hyprland;Wayland;Noctalia;Parametral;
EOF
chmod 0644 /usr/share/wayland-sessions/parametral.desktop

echo "==> Noctalia yapılandırması ve Parametral paleti"
install_noctalia_config() {
  local home="$1"
  [ -d "$home" ] || return 0
  install -d "$home/.config/noctalia/palettes"
  install -m 0644 "$SRC/branding/noctalia/config.toml" "$home/.config/noctalia/config.toml"
  install -m 0644 "$SRC/branding/noctalia/palettes/Parametral.json" \
    "$home/.config/noctalia/palettes/Parametral.json"

  # The palette file carries both modes; this one line selects the answer the installer got.
  sed -i "s/^mode[[:space:]]*=[[:space:]]*\"dark\"/mode = \"$APPEARANCE\"/" \
    "$home/.config/noctalia/config.toml"
  sed -i "s/^mode[[:space:]]*=[[:space:]]*\"light\"/mode = \"$APPEARANCE\"/" \
    "$home/.config/noctalia/config.toml"

  chown -R "$(stat -c %U "$home"):$(stat -c %G "$home")" "$home/.config/noctalia" 2>/dev/null || true
}

install_noctalia_config /etc/skel
if [ -n "$PARAMETRAL_USER" ] && [ -d "/home/$PARAMETRAL_USER" ]; then
  install_noctalia_config "/home/$PARAMETRAL_USER"
fi
for home in /home/*; do
  [ -d "$home" ] || continue
  [ "$home" = "/home/lost+found" ] && continue
  install_noctalia_config "$home"
done

echo "==> tr_TR.UTF-8 locale"
if ! locale -a 2>/dev/null | grep -qi '^tr_TR.utf8$'; then
  sed -i 's/^#\s*\(tr_TR.UTF-8 UTF-8\)/\1/' /etc/locale.gen 2>/dev/null || true
  grep -q '^tr_TR.UTF-8 UTF-8' /etc/locale.gen 2>/dev/null || \
    echo 'tr_TR.UTF-8 UTF-8' >> /etc/locale.gen
  locale-gen
fi

echo "==> done (Hyprland)"
